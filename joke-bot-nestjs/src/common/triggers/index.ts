/**
 * Find a contextual response based on message content
 * Returns null if no keywords matched
 */
export function findContextualResponse(text: string): string | null {
  const lowerText = text.toLowerCase();

  for (const trigger of KEYWORD_TRIGGERS) {
    for (const keyword of trigger.keywords) {
      if (lowerText.includes(keyword)) {
        const randomIndex = Math.floor(Math.random() * trigger.responses.length);
        const response = trigger.responses[randomIndex];
        if (response === undefined) {
          return null;
        }
        return trigger.emoji !== undefined ? `${trigger.emoji} ${response}` : response;
      }
    }
  }

  return null;
}

/**
 * Check if message contains any trigger keyword
 */
export function hasKeywordMatch(text: string): boolean {
  const lowerText = text.toLowerCase();
  return KEYWORD_TRIGGERS.some((trigger) =>
    trigger.keywords.some((keyword) => lowerText.includes(keyword)),
  );
}
